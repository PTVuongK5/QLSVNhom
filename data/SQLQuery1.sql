CREATE PROCEDURE SP_INS_SINHVIEN
    @MASV VARCHAR(20),
    @HOTEN NVARCHAR(100),
    @NGAYSINH DATETIME,
    @DIACHI NVARCHAR(200),
    @MALOP VARCHAR(20),
    @TENDN NVARCHAR(100),
    @MATKHAU VARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS
    (
        SELECT 1
        FROM SINHVIEN
        WHERE MASV = @MASV
        OR TENDN = @TENDN
    )
    BEGIN
        RAISERROR(N'Mã SV hoặc tên đăng nhập đã tồn tại.',16,1);
        RETURN;
    END

    INSERT INTO SINHVIEN
    VALUES
    (
        @MASV,
        @HOTEN,
        @NGAYSINH,
        @DIACHI,
        @MALOP,
        @TENDN,
        HASHBYTES('SHA1',@MATKHAU)
    );

    PRINT N'✅ Thêm sinh viên thành công';
END;
GO


CREATE PROCEDURE SP_SEL_BANGDIEM_BY_MASV
    @MASV VARCHAR(20),
    @MANV VARCHAR(20),
    @MK NVARCHAR(200)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS
    (
        SELECT 1
        FROM SINHVIEN sv
        JOIN LOP l ON sv.MALOP = l.MALOP
        WHERE sv.MASV = @MASV
        AND l.MANV = @MANV
    )
    BEGIN
        RAISERROR(N'Không có quyền xem bảng điểm.',16,1);
        RETURN;
    END

    SELECT
        bd.MASV,
        bd.MAHP,
        CAST(
            DECRYPTBYASYMKEY(
                ASYMKEY_ID(@MANV),
                bd.DIEMTHI,
                @MK
            ) AS NVARCHAR(20)
        ) AS DIEMTHI
    FROM BANGDIEM bd
    WHERE bd.MASV = @MASV;
END;
GO

CREATE PROCEDURE SP_UPSERT_BANGDIEM_ENC
    @MASV VARCHAR(20),
    @MAHP VARCHAR(20),
    @DIEMTHI DECIMAL(5,2),
    @MANV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS
    (
        SELECT 1
        FROM SINHVIEN sv
        JOIN LOP l ON sv.MALOP = l.MALOP
        WHERE sv.MASV = @MASV
        AND l.MANV = @MANV
    )
    BEGIN
        RAISERROR(N'Không có quyền nhập điểm.',16,1);
        RETURN;
    END

    DECLARE @DIEM_ENC VARBINARY(MAX);

    SET @DIEM_ENC =
        ENCRYPTBYASYMKEY(
            ASYMKEY_ID(@MANV),
            CAST(@DIEMTHI AS NVARCHAR(20))
        );

    IF EXISTS
    (
        SELECT 1
        FROM BANGDIEM
        WHERE MASV = @MASV
        AND MAHP = @MAHP
    )
    BEGIN
        UPDATE BANGDIEM
        SET DIEMTHI = @DIEM_ENC
        WHERE MASV = @MASV
        AND MAHP = @MAHP;
    END
    ELSE
    BEGIN
        INSERT INTO BANGDIEM
        VALUES (@MASV,@MAHP,@DIEM_ENC);
    END
END;
GO


-- =========================================
-- PROCEDURE NHÂN VIÊN
-- =========================================

CREATE PROCEDURE SP_INS_PUBLIC_NHANVIEN
    @MANV VARCHAR(20),
    @HOTEN NVARCHAR(100),
    @EMAIL VARCHAR(100),
    @LUONGCB INT,
    @TENDN NVARCHAR(100),
    @MK VARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @SqlCreateKey NVARCHAR(MAX);

    SET @SqlCreateKey =
        'CREATE ASYMMETRIC KEY ' + QUOTENAME(@MANV) +
        ' WITH ALGORITHM = RSA_2048 ENCRYPTION BY PASSWORD = ''' + @MK + '''';

    BEGIN TRY

        EXEC sp_executesql @SqlCreateKey;

        DECLARE @LUONG_ENCRYPTED VARBINARY(MAX);

        SET @LUONG_ENCRYPTED =
            ENCRYPTBYASYMKEY(
                ASYMKEY_ID(@MANV),
                CAST(@LUONGCB AS NVARCHAR(50))
            );

        INSERT INTO NHANVIEN
        VALUES
        (
            @MANV,
            @HOTEN,
            @EMAIL,
            @LUONG_ENCRYPTED,
            @TENDN,
            HASHBYTES('SHA1', @MK),
            @MANV
        );

        PRINT N'✅ Thêm nhân viên thành công';

    END TRY
    BEGIN CATCH
        PRINT N'❌ Lỗi: ' + ERROR_MESSAGE();
    END CATCH
END;
GO

CREATE PROCEDURE SP_SEL_PUBLIC_NHANVIEN
    @TENDN NVARCHAR(100),
    @MK NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT
        MANV,
        HOTEN,
        EMAIL,
        CAST(
            DECRYPTBYASYMKEY(
                ASYMKEY_ID(PUBKEY),
                LUONG,
                @MK
            ) AS NVARCHAR(50)
        ) AS LUONGCB
    FROM NHANVIEN
    WHERE TENDN = @TENDN;
END;
GO


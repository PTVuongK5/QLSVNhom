CREATE PROCEDURE SP_SEL_LOP_BY_MANV
    @MANV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT *
    FROM LOP
    WHERE MANV = @MANV
    ORDER BY MALOP;
END;
GO

CREATE PROCEDURE SP_INS_LOP
    @MALOP VARCHAR(20),
    @TENLOP NVARCHAR(100),
    @MANV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    IF EXISTS (SELECT 1 FROM LOP WHERE MALOP = @MALOP)
    BEGIN
        RAISERROR(N'Mã lớp đã tồn tại.',16,1);
        RETURN;
    END

    INSERT INTO LOP
    VALUES (@MALOP,@TENLOP,@MANV);
END;
GO

CREATE PROCEDURE SP_UPD_LOP
    @MALOP VARCHAR(20),
    @TENLOP NVARCHAR(100),
    @MANV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS
    (
        SELECT 1
        FROM LOP
        WHERE MALOP = @MALOP
        AND MANV = @MANV
    )
    BEGIN
        RAISERROR(N'Không có quyền cập nhật.',16,1);
        RETURN;
    END

    UPDATE LOP
    SET TENLOP = @TENLOP
    WHERE MALOP = @MALOP
    AND MANV = @MANV;
END;
GO

CREATE PROCEDURE SP_DEL_LOP
    @MALOP VARCHAR(20),
    @MANV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS
    (
        SELECT 1
        FROM LOP
        WHERE MALOP = @MALOP
        AND MANV = @MANV
    )
    BEGIN
        RAISERROR(N'Không có quyền xóa.',16,1);
        RETURN;
    END

    IF EXISTS
    (
        SELECT 1
        FROM SINHVIEN
        WHERE MALOP = @MALOP
    )
    BEGIN
    RAISERROR(N'Lớp đã có sinh viên.',16,1);
        RETURN;
    END

    DELETE FROM LOP
    WHERE MALOP = @MALOP
    AND MANV = @MANV;
END;
GO

